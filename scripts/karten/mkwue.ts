import { readFileSync, writeFileSync } from 'node:fs';
import { importOsm } from '../../shared/osmimport';
import { RoadGraph } from '../../shared/geo';
const raw = JSON.parse(readFileSync(process.argv[2], 'utf8'));
let t = Date.now();
const { scenario, notes } = importOsm(raw, { name: 'Würzburg', bbox: raw.bbox });
console.log('import ms', Date.now() - t);
scenario.id = 'scn_ils_wuerzburg';
scenario.name = 'Würzburg';
scenario.ilsName = 'ILS Würzburg';
notes.push('Kartendaten © OpenStreetMap-Mitwirkende (ODbL), bezogen über Overture Maps. Wachenstandorte teils aus Overture Places, Fahrzeugbelegung geschätzt.');
console.log(notes.join('\n'));
console.log('nodes', scenario.nodes.length, 'roads', scenario.roads.length, 'oneway', scenario.roads.filter((r) => r.oneway).length, 'maxspeed', scenario.roads.filter((r) => r.maxspeed).length);
console.log('types', JSON.stringify(scenario.roads.reduce((m: Record<string, number>, r) => ((m[r.type] = (m[r.type] ?? 0) + 1), m), {})));
console.log('stations', scenario.stations.length, scenario.stations.filter((s) => s.kind === 'rettungswache').map((s) => s.name).join('; '));
console.log('hospitals', scenario.hospitals.map((h) => h.name).join('; '));
console.log('towns', scenario.towns.length, scenario.towns.slice(0, 8).map((x) => `${x.name}:${x.radius}`).join(' '));
t = Date.now();
const g = new RoadGraph(scenario);
g.dijkstra(g.nearestNode({ x: scenario.width / 2, y: scenario.height / 2 }), true);
console.log('graph+dijkstra ms', Date.now() - t, 'width km', scenario.width / 1000, 'height km', scenario.height / 1000);
const json = JSON.stringify(scenario);
console.log('json MB', (json.length / 1e6).toFixed(1));
writeFileSync(process.argv[3], json);
